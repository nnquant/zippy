"""Generate both Flight wire bindings from the canonical protobuf schema.

:param --check: Compare generated bytes without changing tracked files.
:raises SystemExit: If generation fails or checked-in files have drifted.
:example: uv run --group protocol scripts/generate_protocol.py --check
"""

from __future__ import annotations

import argparse
from importlib.metadata import version
from pathlib import Path
import subprocess
import sys
import tempfile

import black


def main() -> None:
    """Generate bindings or check that their checked-in contents are current."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for package, expected in (("grpcio-tools", "1.81.1"), ("black", "26.3.1")):
        if version(package) != expected:
            raise SystemExit(
                f"generator version mismatch package=[{package}] required=[{expected}]"
            )
    root = Path(__file__).resolve().parents[1]
    proto = root / "crates/zippy-protocol/proto/zippy/flight/v1"
    with tempfile.TemporaryDirectory(prefix="zippy-protocol-") as temporary:
        output = Path(temporary)
        descriptor = output / "protocol.bin"
        subprocess.run(
            [
                sys.executable,
                "-m",
                "grpc_tools.protoc",
                f"-I{proto}",
                f"--python_out={output}",
                f"--pyi_out={output}",
                f"--descriptor_set_out={descriptor}",
                str(proto / "protocol.proto"),
            ],
            check=True,
            cwd=root,
        )
        subprocess.run(
            [
                "cargo",
                "run",
                "--locked",
                "--manifest-path",
                str(root / "tools/protocol-codegen/Cargo.toml"),
                "--",
                str(descriptor),
                str(output),
            ],
            check=True,
            cwd=root,
        )
        rust = output / "zippy.flight.v1.rs"
        subprocess.run(["rustfmt", "--edition", "2021", str(rust)], check=True, cwd=root)
        pairs = [(rust, root / "crates/zippy-protocol/src/wire.rs")]
        for name in ("protocol_pb2.py", "protocol_pb2.pyi"):
            generated = output / name
            text = black.format_file_contents(
                generated.read_text(encoding="utf-8"),
                fast=False,
                mode=black.Mode(
                    line_length=100,
                    target_versions={black.TargetVersion.PY311},
                    is_pyi=name.endswith(".pyi"),
                ),
            )
            generated.write_bytes(text.encode("utf-8"))
            pairs.append((generated, root / "clients/python/src/zippy_client/_generated" / name))
        drift = []
        for generated, target in pairs:
            if not target.exists() or generated.read_bytes() != target.read_bytes():
                drift.append(str(target.relative_to(root)))
                if not args.check:
                    target.write_bytes(generated.read_bytes())
        if args.check and drift:
            raise SystemExit("generated protocol drift: " + ", ".join(drift))
        print("protocol generation verified" if args.check else "protocol bindings regenerated")


if __name__ == "__main__":
    main()
